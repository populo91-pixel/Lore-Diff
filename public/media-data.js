window.MediaCore = (() => {
  function normalize(value) {
    return value.toLocaleLowerCase("fr").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]/g, "");
  }
  function shuffle(items) {
    const copy = [...items];
    for (let i = copy.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  }
  function matches(game, value) {
    const needle = normalize(value);
    return [game.name, ...game.aliases].some(alias => normalize(alias) === needle);
  }
  function image(game) {
    return "https://shared.fastly.steamstatic.com/store_item_assets/steam/apps/" + game.id + "/header.jpg";
  }
  function store(game) {
    return "https://store.steampowered.com/app/" + game.id + "/";
  }
  async function screenshot(game) {
    const shots = game.shots || [];
    return shots.length ? shots[Math.floor(Math.random() * shots.length)] : image(game);
  }
  async function trailer(game) {
    if (!game.trailer) throw new Error("Aucune bande-annonce audio");
    return { source: game.trailer, title: game.trailerName || "Bande-annonce officielle" };
  }
  return { normalize, shuffle, matches, image, store, screenshot, trailer };
})();

